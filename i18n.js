  function resolveInitialLang() {
    const params = new URLSearchParams(window.location.search);
    const q = (params.get("lang") || "").toLowerCase().split("-")[0];
    if (T[q]) return q;

    try {
      const saved = (localStorage.getItem("framefold_lang") || "").toLowerCase();
      if (T[saved]) return saved;
    } catch (_) {}

    const prefs = Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language || "en"];

    for (const raw of prefs) {
      const base = String(raw || "").toLowerCase().split(/[-_]/)[0];
      if (T[base]) return base;
    }
    return "en";
  }

  function applyLanguage(code, persist) {
    const lang = T[code] ? code : "en";
    const dict = T[lang];
    document.documentElement.lang = lang;

    const page = document.body.getAttribute("data-page") || "home";
    const titleKey = page === "privacy"
      ? "page_privacy_title"
      : page === "terms"
      ? "page_terms_title"
      : page === "support"
      ? "page_support_title"
      : "page_home_title";
    if (dict[titleKey]) document.title = dict[titleKey];

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) el.textContent = dict[key];
    });

    const select = document.getElementById("lang-select");
    if (select && select.value !== lang) select.value = lang;

    document.querySelectorAll("a[href$='.html'], a[href*='.html?']").forEach((a) => {
      const href = a.getAttribute("href");
      if (!href || href.startsWith("http") || href.startsWith("mailto:")) return;
      const base = href.split("?")[0];
      a.setAttribute("href", `${base}?lang=${lang}`);
    });

    if (persist) {
      try { localStorage.setItem("framefold_lang", lang); } catch (_) {}
      const url = new URL(window.location.href);
      url.searchParams.set("lang", lang);
      window.history.replaceState({}, "", url.toString());
    }
  }

  function initLanguageSwitcher() {
    const select = document.getElementById("lang-select");
    if (select) {
      LANGUAGES.forEach((item) => {
        const opt = document.createElement("option");
        opt.value = item.code;
        opt.textContent = `${item.name} (${item.code.toUpperCase()})`;
        select.appendChild(opt);
      });
      select.addEventListener("change", (e) => applyLanguage(e.target.value, true));
    }
    applyLanguage(resolveInitialLang(), false);
  }

  function initComparisonSlider() {
    const range = document.getElementById("split-range");
    const after = document.getElementById("split-after");
    const divider = document.getElementById("split-divider");
    const handle = document.getElementById("split-handle");
    if (!range || !after || !divider || !handle) return;

    const update = (val) => {
      const pct = Math.max(10, Math.min(90, Number(val) || 50));
      after.style.clipPath = `inset(0 0 0 ${pct}%)`;
      divider.style.left = `${pct}%`;
      handle.style.left = `${pct}%`;
    };
    range.addEventListener("input", (e) => update(e.target.value));
    update(range.value);
  }

  document.addEventListener("DOMContentLoaded", () => {
    initLanguageSwitcher();
    initComparisonSlider();
  });
